for n in DROP: FIX[f"#{n}"] = "@drop"
files = {p: open(p, encoding="utf-8").read() for p in sorted(glob.glob("ja/*.txt"))}
for key, body in FIX.items():
    pat = re.compile(rf"^{re.escape(key)}\n(?:.+\n?)*", re.M)
    hits = [(p, m) for p, t in files.items() for m in pat.finditer(t)]
    if len(hits) != 1: print("該当が1件でない", key, len(hits)); continue
    p, m = hits[0]; t = files[p]; tail = "\n" if m.group().endswith("\n") else ""
    files[p] = t[:m.start()] + f"{key}\n{body}" + tail + t[m.end():]
for p, t in files.items(): open(p, "w", encoding="utf-8").write(t)
